# Builds src/map/countries.js: every country's outline (simplified), names and a point inside, for opening and closing
# countries on the world map. Natural Earth 1:50m (public domain); Ukraine within its internationally recognised borders.
#   python3 tools/build-countries.py <cache dir with ne_50m_countries.geojson>
import json, os, sys
from shapely.geometry import shape
from shapely.ops import unary_union
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
g = json.load(open(os.path.join(sys.argv[1], 'ne_50m_countries.geojson')))
feats = {f['properties']['ADM0_A3']: f for f in g['features']}
geoms = {k: shape(f['geometry']).buffer(0) for k, f in feats.items()}
rus = geoms['RUS']; crimea = unary_union([p for p in rus.geoms if 32 < p.centroid.x < 37 and 44 < p.centroid.y < 46.3])
geoms['UKR'] = unary_union([geoms['UKR'], crimea]).buffer(0.002).buffer(-0.002); geoms['RUS'] = rus.difference(crimea.buffer(0.01))
# country names in the game's languages (Natural Earth has these; the rest fall back to English). No Russian.
LANG_FIELDS = { 'uk': 'NAME_UK', 'de': 'NAME_DE', 'es': 'NAME_ES', 'fr': 'NAME_FR', 'it': 'NAME_IT', 'ja': 'NAME_JA', 'ko': 'NAME_KO', 'nl': 'NAME_NL', 'pl': 'NAME_PL',
  'pt-BR': 'NAME_PT', 'sv': 'NAME_SV', 'tr': 'NAME_TR', 'ar': 'NAME_AR', 'hi': 'NAME_HI', 'id': 'NAME_ID', 'vi': 'NAME_VI', 'zh-CN': 'NAME_ZH', 'zh-TW': 'NAME_ZHT' }
out = []
for k, f in feats.items():
    gm = geoms[k].simplify(0.04, preserve_topology=True)
    polys = list(gm.geoms) if gm.geom_type == 'MultiPolygon' else [gm]
    rings = [[[round(x, 2), round(y, 2)] for x, y in p.exterior.coords] for p in polys if p.area > 0.01]
    if not rings: continue
    pr = f['properties']; rp = geoms[k].representative_point()
    row = { 'id': k, 'en': pr.get('NAME_EN') or pr['ADMIN'], 'n': {}, 'c': [round(rp.x, 3), round(rp.y, 3)], 'r': rings }
    for lang, field in LANG_FIELDS.items():   # names under 'n' (a language code like 'id' must not clash with the fields)
        v = pr.get(field)
        if v and v != row['en']: row['n'][lang] = v
    out.append(row)
out.sort(key=lambda c: c['en'])
js = '// Generated by tools/build-countries.py from Natural Earth 1:50m (public domain): outlines, names and a point inside each country.\nwindow.Countries = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'src', 'map', 'countries.js'), 'w').write(js)
print(len(out), 'countries', len(js), 'bytes')
