# Builds the relief of the whole Earth (land and sea floor) from Terrarium elevation tiles at zoom 6
# (Mapzen / AWS open data, s3.amazonaws.com/elevation-tiles-prod, ~2.4 km per pixel at the equator).
#   python3 tools/build-world-dem.py <folder with 6_x_y.png tiles>
# Output: src/dem/world/<col>_<row>.txt — 15° x 15° blocks on a 1/30° grid (~3.7 km), whole metres,
# each row delta-coded, zlib-compressed, base64 (the artifact host only serves text).
# A block holds 453 x 453 samples: one before and two after its 450 cells, so the game can interpolate
# smoothly (Catmull-Rom) inside a block without its neighbours.  Rows go north to south.
import math, os, sys, json, zlib, base64
import numpy as np
from PIL import Image
TILES = sys.argv[1]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'dem', 'world'); os.makedirs(OUT, exist_ok=True)
Z, N = 6, 64
STEP, BLOCK = 1 / 30, 15
CELLS = int(round(BLOCK / STEP)); S = CELLS + 3
cache = {}
def tile(x, y):
    k = (x % N, y)
    if k not in cache:
        a = np.asarray(Image.open(os.path.join(TILES, f'6_{k[0]}_{k[1]}.png')).convert('RGB')).astype(np.float32)
        cache[k] = a[..., 0] * 256 + a[..., 1] + a[..., 2] / 256 - 32768
        if len(cache) > 400: cache.pop(next(iter(cache)))
    return cache[k]
def merc_y(lat):
    lat = np.clip(lat, -85.05, 85.05); s = np.sin(np.radians(lat)); return 0.5 - np.log((1 + s) / (1 - s)) / (4 * np.pi)
def sample(LON, LAT):   # bilinear in the Mercator mosaic
    fx = ((LON + 180) / 360 * N) * 256 - 0.5; fy = merc_y(LAT) * N * 256 - 0.5
    fy = np.clip(fy, 0, N * 256 - 1.001)
    x0 = np.floor(fx).astype(np.int64); y0 = np.floor(fy).astype(np.int64); tx = fx - x0; ty = fy - y0
    out = np.zeros(LON.shape, np.float32)
    def px(X, Y):
        X = X % (N * 256); r = np.zeros(X.shape, np.float32)
        tX, tY = X // 256, Y // 256
        for (a, b) in set(zip(tX.ravel().tolist(), tY.ravel().tolist())):
            m = (tX == a) & (tY == b); r[m] = tile(a, b)[Y[m] % 256, X[m] % 256]
        return r
    y1 = np.minimum(y0 + 1, N * 256 - 1)
    a = px(x0, y0) * (1 - tx) + px(x0 + 1, y0) * tx; b = px(x0, y1) * (1 - tx) + px(x0 + 1, y1) * tx
    return a * (1 - ty) + b * ty
info = {'step': STEP, 'block': BLOCK, 'size': S, 'cols': 360 // BLOCK, 'rows': 180 // BLOCK, 'file': 'dem/world/{c}_{r}.txt'}
total = 0
for r in range(180 // BLOCK):
    for c in range(360 // BLOCK):
        lon0, lat1 = -180 + c * BLOCK, 90 - r * BLOCK
        i = np.arange(-1, CELLS + 2)
        LON, LAT = np.meshgrid(lon0 + i * STEP, lat1 - i * STEP)
        e = np.clip(np.round(sample(LON, LAT)), -11000, 9000).astype(np.int32)
        d = e.copy(); d[:, 1:] = e[:, 1:] - e[:, :-1]; d[1:, 0] = e[1:, 0] - e[:-1, 0]   # deltas along rows, first column down
        raw = zlib.compress(d.astype('<i2').tobytes(), 9)
        txt = base64.b64encode(raw).decode(); total += len(txt)
        open(os.path.join(OUT, f'{c}_{r}.txt'), 'w').write(txt)
    print('row', r, 'done, total', round(total / 1e6, 1), 'MB', flush=True)
open(os.path.join(ROOT, 'src', 'dem', 'world.js'), 'w').write('// Generated by tools/build-world-dem.py: relief of the whole Earth, 15° blocks on a 1/30° grid (Terrarium, Mapzen / AWS open data).\nwindow.WorldDemInfo = ' + json.dumps(info) + ';\n')
