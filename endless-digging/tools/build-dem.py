# Builds the real relief the game walks on, from Terrarium elevation tiles (Mapzen / AWS open data, s3.amazonaws.com/elevation-tiles-prod).
#   python3 tools/build-dem.py <cache dir> [preview.png]
# Output in src/dem/:
#   local.bin   ~20 m grid around the start (Kryvyi Rih), int16 decimetres, rows north to south
#   ukraine.bin ~2 km grid over Ukraine and its neighbours, int16 decimetres
#   dem.js      the boxes and sizes of both grids (window.DemInfo)
import math, os, sys, json
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
CACHE = sys.argv[1]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'dem'); os.makedirs(OUT, exist_ok=True)
import urllib.request

def fetch(url, name):
    p = os.path.join(CACHE, name)
    if not os.path.exists(p):
        with urllib.request.urlopen(url, timeout=120) as r: open(p, 'wb').write(r.read())
    return p
def tile(z, x, y):
    a = np.asarray(Image.open(fetch(f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{z}/{x}/{y}.png', f'terr_{z}_{x}_{y}.png')).convert('RGB')).astype(np.float64)
    return a[..., 0] * 256 + a[..., 1] + a[..., 2] / 256 - 32768
def merc_y(lat):
    s = np.sin(np.radians(lat)); return 0.5 - np.log((1 + s) / (1 - s)) / (4 * np.pi)
def grid(z, box, W, H):
    lon0, lon1, lat0, lat1 = box; n = 2 ** z
    tx0, tx1 = int((lon0 + 180) / 360 * n), int((lon1 + 180) / 360 * n)
    ty0, ty1 = int(merc_y(lat1) * n), int(merc_y(lat0) * n)
    E = np.vstack([np.hstack([tile(z, x, y) for x in range(tx0, tx1 + 1)]) for y in range(ty0, ty1 + 1)])
    lon = lon0 + np.arange(W) / (W - 1) * (lon1 - lon0); lat = lat1 - np.arange(H) / (H - 1) * (lat1 - lat0)   # samples on the box edges
    LON, LAT = np.meshgrid(lon, lat)
    fx = ((LON + 180) / 360 * n - tx0) * 256 - 0.5; fy = (merc_y(LAT) * n - ty0) * 256 - 0.5
    x0 = np.clip(fx.astype(int), 0, E.shape[1] - 2); y0 = np.clip(fy.astype(int), 0, E.shape[0] - 2); tx = np.clip(fx - x0, 0, 1); ty = np.clip(fy - y0, 0, 1)
    a = E[y0, x0] * (1 - tx) + E[y0, x0 + 1] * tx; b = E[y0 + 1, x0] * (1 - tx) + E[y0 + 1, x0 + 1] * tx
    return a * (1 - ty) + b * ty

LOCAL = (33.27, 33.51, 47.83, 47.99)     # about 18 x 18 km around the start
UKR = (21.0, 42.0, 43.0, 53.5)
lw = int(round((LOCAL[1] - LOCAL[0]) / 0.00025)) + 1; lh = int(round((LOCAL[3] - LOCAL[2]) / 0.00018)) + 1   # ~18.7 m x 20 m
uw = int(round((UKR[1] - UKR[0]) / 0.02)) + 1; uh = int(round((UKR[3] - UKR[2]) / 0.02)) + 1                # ~1.5 km x 2.2 km
local = grid(13, LOCAL, lw, lh)
# soften the SRTM speckle (buildings, radar noise) a little: one pass of a 3x3 blur
k = np.pad(local, 1, mode='edge'); local = sum(k[1 + dy:1 + dy + lh, 1 + dx:1 + dx + lw] * w for dy, dx, w in [(dy, dx, (2 if dy == 0 else 1) * (2 if dx == 0 else 1) / 16) for dy in (-1, 0, 1) for dx in (-1, 0, 1)])
ukr = grid(8, UKR, uw, uh)
for name, a in (('local.bin', local), ('ukraine.bin', ukr)):
    np.clip(np.round(a * 10), -32000, 32000).astype('<i2').tofile(os.path.join(OUT, name))
info = { 'local': { 'box': LOCAL, 'w': lw, 'h': lh, 'file': 'dem/local.bin' }, 'ukraine': { 'box': UKR, 'w': uw, 'h': uh, 'file': 'dem/ukraine.bin' } }
open(os.path.join(OUT, 'dem.js'), 'w').write('// Generated by tools/build-dem.py: real relief grids (Terrarium elevation tiles, Mapzen / AWS open data).\nwindow.DemInfo = ' + json.dumps(info) + ';\n')
print('local', lw, lh, local.min(), local.max(), 'ukraine', uw, uh, ukr.min(), ukr.max())
if len(sys.argv) > 2:   # shaded preview of the local grid
    gy, gx = np.gradient(local); hs = np.clip(0.6 + (gx * -0.04 + gy * 0.04), 0, 1)
    h = (local - local.min()) / (local.max() - local.min())
    rgb = np.stack([0.3 + 0.6 * h, 0.55 + 0.3 * h, 0.3 + 0.2 * h], -1) * hs[..., None]
    Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8)).save(sys.argv[2])
